pub(crate) fn closure_random(frag_coord: [f32; 2], sampling_closure: f32) -> f32 {
    let x = (frag_coord[0] as usize) % BLUE_NOISE_EXTENT;
    let y = (frag_coord[1] as usize) % BLUE_NOISE_EXTENT;
    let noise = f32::from(BLUE_NOISE_RED[y * BLUE_NOISE_EXTENT + x]) * BLUE_NOISE_SCALE;
    (noise + sampling_closure).fract()
}

