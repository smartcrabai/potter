pub(crate) fn raytrace_green(frag_coord: [usize; 2]) -> f32 {
    let index =
        (frag_coord[1] % BLUE_NOISE_EXTENT) * BLUE_NOISE_EXTENT + frag_coord[0] % BLUE_NOISE_EXTENT;
    f32::from(BLUE_NOISE_GREEN[index]) * BLUE_NOISE_SCALE
}

