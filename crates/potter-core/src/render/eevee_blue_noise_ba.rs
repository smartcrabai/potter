pub(crate) fn raytrace_ba(frag_coord: [usize; 2]) -> [f32; 2] {
    let index =
        (frag_coord[1] % BLUE_NOISE_EXTENT) * BLUE_NOISE_EXTENT + frag_coord[0] % BLUE_NOISE_EXTENT;
    [
        f32::from(BLUE_NOISE_BLUE[index]) * BLUE_NOISE_SCALE,
        f32::from(BLUE_NOISE_ALPHA[index]) * BLUE_NOISE_SCALE,
    ]
}

