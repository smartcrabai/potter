fn supported(
    feature_id: &str,
    name: &str,
    blender_type: &str,
    pot_ops: &[&str],
    flags: [bool; 7],
) -> Value {
    let ops_present = pot_ops.iter().all(|op| ops::OP_NAMES.contains(op));
    let (status, reason, flags) = if ops_present {
        ("supported", Value::Null, flags)
    } else {
        (
            "not_supported",
            json!("A required typed operation is not implemented."),
            [false; 7],
        )
    };
    feature_row(
        feature_id,
        name,
        blender_type,
        pot_ops,
        flags,
        status,
        &reason,
    )
}

fn unsupported(
    feature_id: &str,
    name: &str,
    blender_type: &str,
    pot_ops: &[&str],
    reason: &str,
) -> Value {
    feature_row(
        feature_id,
        name,
        blender_type,
        pot_ops,
        [false; 7],
        "not_supported",
        &json!(reason),
    )
}

fn partially_supported(
    feature_id: &str,
    name: &str,
    blender_type: &str,
    pot_ops: &[&str],
    reason: &str,
) -> Value {
    feature_row(
        feature_id,
        name,
        blender_type,
        pot_ops,
        [true, true, true, true, true, false, true],
        "partial",
        &json!(reason),
    )
}

