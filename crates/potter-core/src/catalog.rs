fn format_row(
    name: &str,
    direction: [bool; 2],
    features: &[&str],
    requires_blender: bool,
    runtime: &[&str],
    loss_conditions: &[&str],
) -> Value {
    let (status, reason) = match name {
        "blend" | "glb" | "gltf" | "vrm" | "vrm0" | "usda" | "usdc" | "usd" | "usdz"
        | "alembic" | "fbx" | "fbx-binary" | "bvh" | "obj" | "stl" | "ply" | "svg" | "pdf" => {
            ("supported", Value::Null)
        }
        _ => ("not_supported", json!("Format adapter is not implemented.")),
    };
    json!({"format":name,"direction":{"import":direction[0],"export":direction[1]},"features":features,"required_runtime":runtime,"requires_blender":requires_blender,"loss_conditions":loss_conditions,"status":status,"reason":reason})
}

