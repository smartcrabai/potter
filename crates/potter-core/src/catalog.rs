fn vrm_format_row(format: &str) -> Value {
    let mut row = format_row(
        format,
        [true, true],
        &[
            "GLB 2.0 container",
            "avatar metadata and humanoid",
            "expressions",
            "first-person and look-at",
            "spring bones",
            "MToon materials",
        ],
        false,
        &[],
        &[
            "Export: settings not representable by this VRM version are rejected during validation and export.",
            "Custom shader graphs export their supported subset to glTF materials; unsupported graph parts are reported as losses (material.shader_graph.*), and texture references to a missing UV layer fall back to the render layer and are reported as losses (uv.layer_missing).",
            "Import: the file must carry the matching extension (VRMC_vrm for vrm, VRM for vrm0); a glTF extension Potter does not decode and a VRM feature Potter cannot hold are reported as losses (vrm.extension.*, vrm.meta.*, vrm.humanoid.*, vrm.expression.*, vrm.first_person.*, vrm.look_at, vrm.spring.*, vrm.mtoon.*).",
            "Import append: the avatar is not attached when the scene already has an avatar or an imported node, data, material or image ID already exists (vrm.avatar).",
        ],
    );
    let mut features = row["features"].as_array().cloned().unwrap_or_default();
    features.extend(
        crate::model::AVATAR_FEATURE_DESCRIPTORS
            .iter()
            .map(|descriptor| json!(descriptor.feature_id)),
    );
    row["features"] = Value::Array(features);
    row
}

fn format_row(
    name: &str,
    direction: [bool; 2],
    features: &[&str],
    requires_blender: bool,
    runtime: &[&str],
    loss_conditions: &[&str],
) -> Value {
    let (status, reason) = match name {
        "blend" | "glb" | "gltf" | "vrm" | "vrm0" | "usda" | "usdc" | "usd" | "usdz"
        | "alembic" | "fbx" | "fbx-binary" | "bvh" | "obj" | "stl" | "ply" | "svg" | "pdf" => {
            ("supported", Value::Null)
        }
        _ => ("not_supported", json!("Format adapter is not implemented.")),
    };
    json!({"format":name,"direction":{"import":direction[0],"export":direction[1]},"features":features,"required_runtime":runtime,"requires_blender":requires_blender,"loss_conditions":loss_conditions,"status":status,"reason":reason})
}

