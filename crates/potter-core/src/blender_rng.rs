const LOW_SEED: u64 = 0x330E;
const MULTIPLIER: u64 = 0x5_DEEC_E66D;
const ADDEND: u64 = 0xB;
const STATE_MASK: u64 = 0x0000_FFFF_FFFF_FFFF;

/// `RandomNumberGenerator` from `BLI_rand.hh`: a 48-bit LCG whose output is `state >> 17`.
#[derive(Clone, Copy, Debug)]
pub(crate) struct BlenderRng {
    state: u64,
}

impl BlenderRng {
    /// `BLI_rng_seed`: direct seeding.
    pub(crate) fn seed(seed: u32) -> Self {
        Self {
            state: (u64::from(seed) << 16) | LOW_SEED,
        }
    }

    /// `BLI_rng_srandom` / `RandomNumberGenerator::seed_random`: hashed seeding.
    pub(crate) fn seed_random(seed: u32) -> Self {
        let mut rng =
            Self::seed(seed.wrapping_add(u32::from(HASH_UCHAR_512[usize::from(seed as u8)])));
        let mut value = rng.get_uint32();
        rng = Self::seed(value.wrapping_add(u32::from(HASH_UCHAR_512[usize::from(value as u8)])));
        value = rng.get_uint32();
        Self::seed(value.wrapping_add(u32::from(HASH_UCHAR_512[usize::from(value as u8)])))
    }

    fn step(&mut self) {
        self.state = MULTIPLIER.wrapping_mul(self.state).wrapping_add(ADDEND) & STATE_MASK;
    }

    pub(crate) fn get_uint32(&mut self) -> u32 {
        self.step();
        (self.state >> 17) as u32
    }

    pub(crate) fn get_int32(&mut self) -> i32 {
        self.step();
        (self.state >> 17) as i32
    }

    /// `BLI_rng_get_float`: `float(int32) / 2^31`, never 1.0.
    pub(crate) fn get_float(&mut self) -> f32 {
        self.get_int32() as f32 / 2_147_483_648.0_f32
    }
}

#[cfg(test)]
mod tests {
    use super::BlenderRng;

    #[test]
    fn direct_seed_matches_blender_rng_sequence() {
        let mut rng = BlenderRng::seed(1);
        assert_eq!(rng.get_uint32(), 89_400_484);
        assert_eq!(rng.get_int32(), 976_015_093);

        let mut rng = BlenderRng::seed(1);
        assert_eq!(rng.get_float(), 0.041_630_343);
        assert_eq!(rng.get_float(), 0.454_492_45);
    }
}
