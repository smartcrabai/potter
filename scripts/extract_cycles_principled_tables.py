#!/usr/bin/env python3
"""Extract the GGX albedo lookup tables of Cycles into a Rust module.

Usage:
    python3 scripts/extract_cycles_principled_tables.py <shader.tables> <output.rs>

The input is `intern/cycles/scene/shader.tables` at Blender v5.2.2:
https://raw.githubusercontent.com/blender/blender/v5.2.2/intern/cycles/scene/shader.tables

Only the arrays listed in `TABLES` are extracted. Literals are copied verbatim apart from the C
`f` suffix, and each array's element count is checked against its declared size.
"""

import re
import sys
from pathlib import Path

SOURCE_PATH = "intern/cycles/scene/shader.tables"
SCRIPT_PATH = "scripts/extract_cycles_principled_tables.py"
BLENDER_VERSION = "v5.2.2"

WRAP_WIDTH = 100
INDENT = "    "

# (C array name, Rust static name, declared element count)
TABLES = [
    ("table_ggx_E", "GGX_E", 1024),
    ("table_ggx_Eavg", "GGX_E_AVG", 32),
    ("table_ggx_gen_schlick_ior_s", "GGX_GEN_SCHLICK_IOR_S", 4096),
    ("table_sheen_ltc", "SHEEN_LTC", 3072),
    ("table_ggx_glass_E", "GGX_GLASS_E", 4096),
    ("table_ggx_glass_Eavg", "GGX_GLASS_E_AVG", 256),
    ("table_ggx_glass_inv_E", "GGX_GLASS_INV_E", 4096),
    ("table_ggx_glass_inv_Eavg", "GGX_GLASS_INV_E_AVG", 256),
]

# Statics whose Cycles literals include a value that clippy's `approx_constant` lint reads as a math
# constant: the sheen table holds ln 2 as 0.69314. The literal stays verbatim, and the expectation is
# explicit, so a table that stops containing it fails the build rather than hiding the lint.
APPROX_CONSTANT_TABLES = {"SHEEN_LTC"}
APPROX_CONSTANT_EXPECT = [
    "#[expect(",
    "    clippy::approx_constant,",
    '    reason = "Cycles\' sheen table holds ln 2 as 0.69314 verbatim"',
    ")]",
]

# Float literal as written in the Cycles source, with the C `f` suffix already removed.
# Requiring a decimal point keeps every literal valid Rust without reformatting it.
LITERAL_RE = re.compile(r"-?\d+\.\d+(?:[eE][+-]?\d+)?")


def fail(message):
    sys.exit(f"extract_cycles_principled_tables: {message}")


def strip_c_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def extract_array(text, name, size):
    pattern = re.compile(
        r"static\s+const\s+float\s+" + re.escape(name) + r"\[(\d+)\]\s*=\s*\{(.*?)\}\s*;",
        re.S,
    )
    matches = list(pattern.finditer(text))
    if len(matches) != 1:
        fail(f"expected exactly one definition of {name}, found {len(matches)}")
    match = matches[0]

    declared = int(match.group(1))
    if declared != size:
        fail(f"{name} is declared with size {declared}, expected {size}")

    values = []
    for raw in strip_c_comments(match.group(2)).split(","):
        token = raw.strip()
        if not token:
            continue
        if token[-1] not in "fF":
            fail(f"{name}: literal {token!r} has no C float suffix")
        literal = token[:-1]
        if not LITERAL_RE.fullmatch(literal):
            fail(f"{name}: unsupported literal {token!r}")
        values.append(literal)

    if len(values) != size:
        fail(f"{name}: found {len(values)} elements, expected {size}")
    return values


def wrap_values(values):
    lines = []
    current = ""
    for value in values:
        item = f"{value},"
        if not current:
            current = INDENT + item
        elif len(current) + 1 + len(item) <= WRAP_WIDTH:
            current += " " + item
        else:
            lines.append(current)
            current = INDENT + item
    if current:
        lines.append(current)
    return lines


def group_fraction_digits(literal):
    """Return a float literal with its fraction digits grouped in threes, e.g. 0.980405 -> 0.980_405.

    The digits are unchanged, so the value is exactly the source value. clippy::unreadable_literal
    (denied by the workspace's pedantic lints) requires the separators.
    """
    integer, dot, fraction = literal.partition(".")
    if not dot or not fraction or "e" in literal or "E" in literal:
        return literal
    grouped = "_".join(fraction[i : i + 3] for i in range(0, len(fraction), 3))
    return f"{integer}.{grouped}"


def render_static(rust_name, values):
    attributes = ["#[rustfmt::skip]"]
    if rust_name in APPROX_CONSTANT_TABLES:
        attributes = [*APPROX_CONSTANT_EXPECT, *attributes]
    lines = [
        *attributes,
        f"pub(crate) static {rust_name}: [f32; {len(values)}] = [",
        *wrap_values([group_fraction_digits(value) for value in values]),
        "];",
    ]
    return "\n".join(lines)


def render(sections):
    header = [
        "//! Generated by `" + SCRIPT_PATH + "` from",
        "//! `" + SOURCE_PATH + "` at Blender " + BLENDER_VERSION + ".",
        "//! Do not edit by hand; re-run the script to regenerate.",
        "//!",
        "//! Values are the Cycles literals verbatim, with the C `f` suffix removed. Each table is",
        "//! stored row-major with `x` fastest, as `table[z][y][x]`.",
    ]
    body = "\n\n".join(render_static(rust_name, values) for rust_name, values in sections)
    return "\n".join(header) + "\n\n" + body + "\n"


def main(argv):
    if len(argv) != 3:
        sys.exit(f"usage: python3 {SCRIPT_PATH} <shader.tables> <output.rs>")
    input_path, output_path = Path(argv[1]), Path(argv[2])

    text = input_path.read_text(encoding="utf-8")
    sections = []
    for c_name, rust_name, size in TABLES:
        sections.append((rust_name, extract_array(text, c_name, size)))

    output_path.write_text(render(sections), encoding="utf-8")
    for rust_name, values in sections:
        print(f"{rust_name}: {len(values)} values")


if __name__ == "__main__":
    main(sys.argv)
