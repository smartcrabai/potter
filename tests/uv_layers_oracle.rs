//! Blender oracle for multiple UV layers.
//!
//! Potter imports one `.blend` with three UV layers, a pinned layer, active and render indices that
//! differ from the defaults, and two materials (one with no UV Map node, one whose texture reads
//! `Detail`). It exports the scene to each UV-carrying format. Blender re-imports every Potter file
//! and the file Blender's own exporter wrote from the same scene.
//!
//! Each case has one expected layer list, Blender's: the layers Blender's re-import of its own
//! export yields, in order, each paired with the fixture layer it carries. Layers are compared per
//! loop. A loop record is the corner position and corner normal (world space) and the UV in
//! Blender's native V-up convention; the `.blend` leg also compares pins. No V flip happens in this
//! test: Blender's V-up values are compared with Blender's V-up values, and Potter's V-down storage
//! is only seen through Blender's import.
//!
//! Loops come from `DUMP_SCRIPT` (this file, regenerated by Blender on every run; there is no
//! checked-in fixture file). The dump lists every loop in loop order and collapses nothing. Two
//! topologies are compared:
//! - `Faces` (`.blend`, USD, OBJ, PLY, Alembic, FBX): the cube's six quads keep their 24 face
//!   corners. Each side is sorted by record and the sorted lists are compared element by element.
//!   Duplicate loops are counted.
//! - `Triangles` (glTF): Blender splits each quad into two triangles, so there are 36 loops. A
//!   re-import may pick either diagonal, so each loop of one side must have a matching loop on the
//!   other side (both ways). The loop count is still checked exactly.
//!
//! Every layer is checked twice: Blender's own export against the fixture layer it carries, and
//! Potter's export against Blender's own export. Both must agree with the same loop count.
//!
//! Skips without Blender, as the other Blender-gated tests do. `POTTER_REQUIRE_BLENDER` turns the
//! skip into a failure.

