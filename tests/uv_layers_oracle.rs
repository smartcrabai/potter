type TestResult<T = ()> = Result<T, Box<dyn Error>>;

/// Blender-convention tolerance for loop positions, normals and UVs.
const TOLERANCE: f64 = 1.0e-5;
/// Tolerance for store values after a `.blend` round trip (float32 storage in Blender).
const STORE_TOLERANCE: f64 = 1.0e-9;

/// Loops of the cube's six quads: one per face corner.
const FACE_LOOPS: usize = 24;
/// Loops after each quad is split into two triangles: 6 quads x 2 triangles x 3 corners.
const TRIANGLE_LOOPS: usize = 6 * 2 * 3;

/// Layers of the fixture in creation order, with the active (`Detail`, index 2) and render
/// (`Light`, index 1) indices that differ from the defaults.
const SOURCE_ACTIVE: i64 = 2;
const SOURCE_RENDER: i64 = 1;

/// Source order: the layers of the fixture as `(name after re-import, fixture layer)`.
const IN_SOURCE_ORDER: &[(&str, &str)] =
    &[("Base", "Base"), ("Light", "Light"), ("Detail", "Detail")];

/// How a format's re-import lays out the cube's loops.
#[derive(Clone, Copy)]
enum Topology {
    /// One loop per face corner of the six quads.
    Faces,
    /// Each quad is split into two triangles, so a corner can appear as two loops.
    Triangles,
}

/// One exported format.
struct Case {
    format: &'static str,
    extension: &'static str,
    /// Potter's FBX writer rejects material node trees, so only Potter's FBX export uses
    /// `plain.blend`; Blender's own FBX export uses `textured.blend`.
    source: &'static str,
    allow_lossy: bool,
    /// Layers Potter reports as `mesh.uv_layer` losses for the format.
    lost_layers: usize,
    topology: Topology,
    /// Loops in every re-import of the format.
    loops: usize,
    /// Blender's expected layers after re-import of its own export, in order, as
    /// `(name after re-import, fixture layer it carries)`.
    layers: &'static [(&'static str, &'static str)],
}

