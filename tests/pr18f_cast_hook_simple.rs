/// Blender 5.2.2 oracle (`fixtures/pr18f_hook/bevel_origin_oracle.json`, generated by
/// `generate_bevel_origin_oracle.py`): a listed Hook on source vertex 0 after this bevel moves no
/// output vertex, because no bevel output vertex carries an original index. The earlier expectation
/// (bevel points of source vertex 0 move) is not Blender's behaviour in 5.2.2.
#[test]
fn hook_uses_bevel_example_indices() {
    let oracle: Value =
        serde_json::from_str(include_str!("fixtures/pr18f_hook/bevel_origin_oracle.json"))
            .expect("parse bevel origin oracle");
    let mesh = Mesh::box_mesh(BoxParams {
        size: DVec3::splat(2.0),
    })
    .unwrap();
    let bevel = modifier(
        "bevel",
        json!({
            "width": 0.1,
            "segments": 2,
            "affect": "EDGES",
            "limit_method": "NONE",
        }),
        None,
    );
    let before = evaluate_modifiers(&mesh, std::slice::from_ref(&bevel), SUBJECT_NAME).unwrap();
    let after =
        evaluate_modifiers(&mesh, &[bevel, translated_index_hook(&[0])], SUBJECT_NAME).unwrap();
    let output_vertices = oracle["output_vertices"]
        .as_u64()
        .expect("oracle vertex count");
    assert_eq!(before.vertices.len() as u64, output_vertices);
    assert_eq!(after.vertices.len(), before.vertices.len());
    let carried_by_source_zero = oracle["origin_of_output_vertex"]
        .as_object()
        .expect("oracle origin map")
        .values()
        .filter(|sources| {
            sources
                .as_array()
                .is_some_and(|sources| sources.iter().any(|source| source.as_u64() == Some(0)))
        })
        .count();
    let moved = before
        .vertices
        .iter()
        .zip(&after.vertices)
        .filter(|(before, after)| (after.co - before.co).length() > TOLERANCE)
        .count();
    assert_eq!(
        carried_by_source_zero, 0,
        "Blender oracle: no bevel vertex carries source 0"
    );
    assert_eq!(moved, carried_by_source_zero);
}

/// Decimate's `BMesh` keeps `v_other` even when it is not the first weighted source.
#[test]
fn hook_uses_decimate_destination_survivor() {
    let mut mesh = Mesh::new();
    let positions = [
        DVec3::Z,
        DVec3::X,
        DVec3::Y,
        DVec3::NEG_X,
        DVec3::NEG_Y,
        DVec3::NEG_Z,
    ];
    let vertices: Vec<_> = positions
        .into_iter()
        .map(|position| mesh.insert_vertex(position).unwrap())
        .collect();
    mesh.insert_edge([vertices[2], vertices[1]]).unwrap();
    for face in [
        vec![vertices[0], vertices[1], vertices[2]],
        vec![vertices[0], vertices[2], vertices[3]],
        vec![vertices[0], vertices[3], vertices[4]],
        vec![vertices[0], vertices[4], vertices[1]],
        vec![vertices[5], vertices[2], vertices[1]],
        vec![vertices[5], vertices[3], vertices[2]],
        vec![vertices[5], vertices[4], vertices[3]],
        vec![vertices[5], vertices[1], vertices[4]],
    ] {
        mesh.insert_face(face, 0).unwrap();
    }
    mesh.attributes.insert(
        "vertex_groups".to_owned(),
        json!({"Collapse": {"v1": 1.0, "v2": 1.0}}),
    );
    let decimate = modifier(
        "decimate",
        json!({
            "decimate_type": "COLLAPSE",
            "ratio": 0.75,
            "vertex_group": "Collapse",
            "vertex_group_factor": 1.0,
            "use_collapse_triangulate": false,
        }),
        None,
    );
    let decimated =
        evaluate_modifiers(&mesh, std::slice::from_ref(&decimate), SUBJECT_NAME).unwrap();
    assert_eq!(decimated.vertices.len(), 5);
    // Blender 5.2.2 oracle (`fixtures/pr18f_hook/decimate_origin_oracle.json`, generated by
    // `generate_decimate_origin_oracle.py`): a collapse survivor keeps its source index, so the listed
    // source 0 moves output 0 only. Blender rejects duplicate indices, so the list is [6, 0].
    let oracle: Value = serde_json::from_str(include_str!(
        "fixtures/pr18f_hook/decimate_origin_oracle.json"
    ))
    .expect("parse decimate origin oracle");
    let hooked = evaluate_modifiers(
        &mesh,
        &[decimate, translated_index_hook_with_values(&json!([6, 0]))],
        SUBJECT_NAME,
    )
    .unwrap();
    let expected_moved: Vec<usize> = oracle["hook_6_0_moved"]
        .as_array()
        .expect("oracle moved list")
        .iter()
        .map(|index| usize::try_from(index.as_u64().expect("oracle index")).expect("index"))
        .collect();
    let moved: Vec<usize> = (0..hooked.vertices.len())
        .filter(|&index| {
            (hooked.vertices[index].co - decimated.vertices[index].co).length() > TOLERANCE
        })
        .collect();
    assert_eq!(moved, expected_moved);
    for &index in &moved {
        assert!(
            hooked.vertices[index]
                .co
                .distance(decimated.vertices[index].co + DVec3::X)
                < TOLERANCE
        );
    }
}

