fn subject() -> Mesh {
    let mut mesh = Mesh::new();
    for position in SUBJECT {
        mesh.insert_vertex(DVec3::from_array(position)).unwrap();
    }
    mesh
}

/// The subject with vertex group `G` carrying `WEIGHTS`.
fn weighted_subject() -> Mesh {
    let mut mesh = subject();
    let weights: serde_json::Map<String, Value> = WEIGHTS
        .iter()
        .enumerate()
        .map(|(index, weight)| (format!("v{index}"), json!(weight)))
        .collect();
    mesh.attributes
        .insert("vertex_groups".to_owned(), json!({ "G": weights }));
    mesh
}

/// A modifier as the scene hands it over: its reference is already resolved into `object_matrix`.
fn modifier(modifier_type: &str, params: Value, object_matrix: Option<[f64; 16]>) -> Modifier {
    Modifier {
        id: Id::new("modifier_under_test").unwrap(),
        modifier_type: modifier_type.to_owned(),
        name: modifier_type.to_owned(),
        enabled: true,
        params: serde_json::from_value(params).unwrap(),
        binding_data: None,
        runtime: ModifierRuntime {
            object_matrix,
            ..ModifierRuntime::default()
        },
    }
}

/// A curve modifier whose path is given in curve-local space; the scene places it in the subject.
fn curve_modifier(params: Value, object_matrix: Option<[f64; 16]>, path: &[[f64; 3]]) -> Modifier {
    let mut modifier = modifier("curve", params, object_matrix);
    let to_subject =
        object_matrix.map_or(DMat4::IDENTITY, |matrix| DMat4::from_cols_array(&matrix));
    let mut target = Mesh::new();
    for point in path {
        target
            .insert_vertex(to_subject.transform_point3(DVec3::from_array(*point)))
            .unwrap();
    }
    modifier.runtime.target_mesh = Some(serde_json::to_value(target).unwrap());
    modifier
}

fn assert_positions(result: &Mesh, expected: &[[f64; 3]; 8]) {
    assert_eq!(result.vertices.len(), expected.len());
    for (vertex, expected) in result.vertices.iter().zip(expected) {
        let expected = DVec3::from_array(*expected);
        assert!(
            vertex.co.distance(expected) < TOLERANCE,
            "vertex {} is {:?}, Blender gives {:?}",
            vertex.id,
            vertex.co,
            expected
        );
    }
}

